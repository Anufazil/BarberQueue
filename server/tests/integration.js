 const serving = await Queue.findOne({barber:b1._id,status:'SERVING'});
 await call('PATCH','/queue/'+b1._id+'/finish',{queueId:q1._id},b.token,409);
 assert.equal(await Queue.countDocuments({barber:b1._id,status:'SERVING'}),1);count++;
 await call('PATCH','/queue/'+b1._id+'/finish',{},b.token,400);
 await call('PATCH','/queue/skip/'+serving._id,{},b.token);
 for (const entry of await Queue.find({ status: { $in:['WAITING','SERVING'] } })) await service.cancelQueue(entry._id,admin);
 await call('PATCH','/barbers/'+b1._id+'/status',{status:'BREAK'},b.token);
 await call('POST','/queue/join',{barberId:b1._id,customerName:'Break Customer',phone:'9555555555'},null,409);
