 const bOther = await call('POST','/auth/login',{email:'barber2@example.test',password});
 const connect = async token => {
   const socket = require('socket.io-client').io(base, { auth: { token }, reconnection:false }); sockets.push(socket);
   await new Promise((resolve,reject)=>{socket.once('connect',resolve);socket.once('connect_error',reject);}); return socket;
 };
 const adminSocket = await connect(a.token), ownSocket = await connect(b.token), otherSocket = await connect(bOther.token);
