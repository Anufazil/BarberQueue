 await call('DELETE','/barbers/'+b1._id,undefined,a.token,409);
 await call('PATCH','/queue/'+b1._id+'/next',{},b.token);
 await call('PATCH','/queue/'+b1._id+'/next',{},b.token,409);
 await call('PATCH','/queue/public/cancel',{accessToken:q1.accessToken},null,409);
 await call('PATCH','/barbers/'+b1._id+'/status',{status:'AVAILABLE'},b.token,409);
 await call('PATCH','/queue/'+b1._id+'/finish',{queueId:q1._id},b.token);
 await call('PATCH','/queue/skip/'+q1._id,{},b.token,409);
 assert.equal((await call('GET','/queue/status/'+q1.accessToken)).data.status,'COMPLETED');
 await call('PATCH','/queue/public/cancel',{accessToken:q2.accessToken});
 assert.equal((await call('GET','/queue/status/'+q2.accessToken)).data.status,'CANCELLED');
