 await call('PATCH','/barbers/'+b2._id+'/status',{status:'BREAK'},b.token,403);
 await call('PATCH','/barbers/'+b1._id+'/status',{status:'INVALID'},b.token,400);
 await call('GET','/queue/not-an-id',undefined,b.token,400);
 await call('GET','/auth/me',undefined,'bad-token',401);
 const expired = require('jsonwebtoken').sign({id:admin._id},process.env.JWT_SECRET,{expiresIn:-1});
 await call('GET','/auth/me',undefined,expired,401);
 const q1 = (await call('POST','/queue/join',{ barberId:b1._id,customerName:'First Customer',phone:'9111111111'},null,201)).data.queue;
