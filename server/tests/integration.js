 assert.equal(events[0].length,1);assert.equal(events[1].length,1);assert.equal(events[2].length,0);
 assert(!JSON.stringify(events).includes('DO-NOT-BROADCAST'));count+=4;

 await call('GET','/auth/me',undefined,b.token);
